"""Build the Mars rover map (Jezero crater) from NASA Mars Trek tiles.

Heights are APPROXIMATE: Mars Trek serves the MGS MOLA + Mars Express HRSC elevation only as a
colour-coded hillshade, so we read the colour (hue) back into relative height and stretch it to
Jezero's real relief (about 700 m from crater floor to rim). The picture is the MRO CTX mosaic.

Writes missions/rover/data/terrain-mars.js and missions/rover/assets/mars-hillshade.png
Run from the repo root:  python scripts/build_mars_terrain.py   (needs Pillow)
"""
import colorsys
import io
import json
import math
import subprocess
import urllib.request
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
OUT_DATA = ROOT / "missions" / "rover" / "data" / "terrain-mars.js"
OUT_IMG = ROOT / "missions" / "rover" / "assets" / "mars-hillshade.png"

BOX = (77.15, 18.15, 77.75, 18.75)  # lon min, lat min, lon max, lat max (degrees): western Jezero + delta
N = 48
RELIEF_M = 700.0
KM_PER_DEG = 3389.5 * math.pi / 180  # along a meridian
URL = "https://trek.nasa.gov/tiles/Mars/EQ/{layer}/1.0.0/default/default028mm/{z}/{r}/{c}.{ext}"
HEIGHT = ("Mars_MOLA_blend200ppx_HRSC_ClrShade_clon0dd_200mpp_lzw", 8, "png")
PICTURE = ("Jezero_CTX_BlockAdj_dd", 10, "png")


def get(url):
    try:
        with urllib.request.urlopen(url, timeout=30) as r:
            return r.read()
    except Exception:
        return subprocess.run(["curl.exe", "-sf", url], check=True, capture_output=True).stdout


def mosaic(layer, z, ext):
    deg = 180 / 2 ** z
    c0, c1 = int((BOX[0] + 180) // deg), int((BOX[2] + 180) // deg)
    r0, r1 = int((90 - BOX[3]) // deg), int((90 - BOX[1]) // deg)
    img = Image.new("RGB", ((c1 - c0 + 1) * 256, (r1 - r0 + 1) * 256))
    for r in range(r0, r1 + 1):
        for c in range(c0, c1 + 1):
            tile = Image.open(io.BytesIO(get(URL.format(layer=layer, z=z, r=r, c=c, ext=ext)))).convert("RGB")
            img.paste(tile, ((c - c0) * 256, (r - r0) * 256))
    px = 256 / deg
    left, top = (BOX[0] + 180 - c0 * deg) * px, (90 - BOX[3] - r0 * deg) * px
    return img.crop((round(left), round(top), round(left + (BOX[2] - BOX[0]) * px), round(top + (BOX[3] - BOX[1]) * px)))


def hue_height(rgb):
    h, s, v = colorsys.rgb_to_hsv(*(x / 255 for x in rgb))
    if s < 0.15:  # near white/grey: the highest end of the ramp
        return 1.0
    hue = h * 360
    if hue > 300:  # magenta wraps to the lowest end
        hue = 300
    return 1 - hue / 300  # red/white = high, blue/purple = low


def main():
    hm = mosaic(*HEIGHT).filter(ImageFilter.GaussianBlur(2))
    w, h = hm.size
    grid = []
    for j in range(N):
        for i in range(N):
            box = hm.crop((i * w // N, j * h // N, (i + 1) * w // N, (j + 1) * h // N)).resize((4, 4))
            vals = [hue_height(p) for p in (box.get_flattened_data() if hasattr(box, "get_flattened_data") else box.getdata())]
            grid.append(sum(vals) / len(vals))
    lo, hi = min(grid), max(grid)
    height_m = [(g - lo) / (hi - lo) * RELIEF_M for g in grid]
    cell_km = (BOX[3] - BOX[1]) * KM_PER_DEG / N
    slope = []
    for j in range(N):
        for i in range(N):
            def H(a, b):
                return height_m[min(N - 1, max(0, b)) * N + min(N - 1, max(0, a))]
            gx = (H(i + 1, j) - H(i - 1, j)) / (2 * cell_km * 1000)
            gy = (H(i, j + 1) - H(i, j - 1)) / (2 * cell_km * 1000)
            deg = math.degrees(math.atan(math.hypot(gx, gy)))
            slope.append(0 if deg < 4 else 1 if deg < 7 else 2 if deg < 10 else 3)
    pic = mosaic(*PICTURE).convert("L").resize((480, 480), Image.LANCZOS)
    OUT_IMG.parent.mkdir(parents=True, exist_ok=True)
    pic.save(OUT_IMG, optimize=True)
    shade = [round(sum(pic.crop((i * 10, j * 10, i * 10 + 10, j * 10 + 10)).resize((1, 1)).getpixel((0, 0)) for _ in [0])) for j in range(N) for i in range(N)]
    meta = {
        "source": "NASA Mars Trek: MGS MOLA + Mars Express HRSC colour hillshade (heights read from colour, approximate) and MRO CTX Jezero mosaic",
        "box_deg": BOX, "cell_m": round(cell_km * 1000), "relief_m": RELIEF_M,
        "slopeClasses": ["<4 deg", "4-7 deg", "7-10 deg", ">10 deg (at this coarse scale)"],
        "approximate": True,
    }
    data = {"n": N, "meta": meta, "slope": "".join(map(str, slope)), "elev": [round(x / RELIEF_M * 255) for x in height_m], "shade": shade}
    OUT_DATA.write_text("// Generated by scripts/build_mars_terrain.py from NASA Mars Trek data. Heights are approximate.\n"
                        f"export const TERRAIN_MARS = {json.dumps(data, separators=(',', ':'))};\n", encoding="utf-8")
    print("cell", round(cell_km * 1000), "m; slope classes", [slope.count(k) for k in range(4)], "height range", round(min(height_m)), round(max(height_m)))


if __name__ == "__main__":
    main()
